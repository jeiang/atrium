package toolset

import (
	"fmt"
	"strings"

	"github.com/jeiang/atrium/internal/assistant/tool"
)

// Render writes the tool catalog as Markdown. The output is deterministic so
// the drift check can compare it byte for byte.
func Render(tools []tool.Tool) string {
	var b strings.Builder
	b.WriteString("# Tool catalog\n\n")
	b.WriteString("Generated by `just tools-docs` from `internal/assistant/toolset`. Do not edit by hand.\n\n")
	b.WriteString("| Tool | Effect | Run kinds | Flags | Undo | Description |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n",
			t.Name, t.Effect, kinds(t.Contexts), flags(t.Flags), undo(t.Undo), cell(t.Description))
	}
	return b.String()
}

func kinds(ks tool.Kinds) string {
	if len(ks) == 0 {
		return "—"
	}
	out := make([]string, len(ks))
	for i, k := range ks {
		out[i] = string(k)
	}
	return strings.Join(out, ", ")
}

func flags(f tool.Flags) string {
	var out []string
	if f.UntrustedOutput {
		out = append(out, "untrusted_output")
	}
	if f.PrivateData {
		out = append(out, "private_data")
	}
	if f.ExternalEffect {
		out = append(out, "external_effect")
	}
	if f.Web {
		out = append(out, "web")
	}
	if len(out) == 0 {
		return "—"
	}
	return strings.Join(out, ", ")
}

func undo(op string) string {
	if op == "" {
		return "—"
	}
	return "`" + op + "`"
}

func cell(text string) string {
	text = strings.ReplaceAll(text, "|", `\|`)
	return strings.Join(strings.Fields(text), " ")
}
