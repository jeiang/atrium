package py

import "testing"

func TestStrptimeDate(t *testing.T) {
	for _, c := range []struct {
		in      string
		ok      bool
		y, m, d int
	}{
		{"2026-10-06", true, 2026, 10, 6},
		{"2026-1-5", true, 2026, 1, 5},
		{"2026-01-05", true, 2026, 1, 5},
		{"2026-1-05", true, 2026, 1, 5},
		{"2026-01-5", true, 2026, 1, 5},
		{"2026-02-29", false, 0, 0, 0},
		{"2024-02-29", true, 2024, 2, 29},
		{"2026-13-01", false, 0, 0, 0},
		{"2026-00-10", false, 0, 0, 0},
		{"2026-10-00", false, 0, 0, 0},
		{"2026-10-32", false, 0, 0, 0},
		{"2026-10-31", true, 2026, 10, 31},
		{"2026-11-31", false, 0, 0, 0},
		{"2026-10- 6", true, 2026, 10, 6},
		{"2026-10-06 ", false, 0, 0, 0},
		{"2026- 1-5", false, 0, 0, 0},
		{"2026-1-1", true, 2026, 1, 1},
		{"0000-01-01", false, 0, 0, 0},
		{"0001-01-01", true, 1, 1, 1},
		{"9999-12-31", true, 9999, 12, 31},
		{"26-10-06", false, 0, 0, 0},
		{"2026-10", false, 0, 0, 0},
		{"2026-10-", false, 0, 0, 0},
		{"2026-100-6", false, 0, 0, 0},
		{"2026-10-006", false, 0, 0, 0},
		{"2026/10/06", false, 0, 0, 0},
		{"2026-1--5", false, 0, 0, 0},
		{"2026-10-3", true, 2026, 10, 3},
		{"2026-10-30", true, 2026, 10, 30},
		{"2026-12-1", true, 2026, 12, 1},
		{"2026-012-01", false, 0, 0, 0},
		{"a026-10-06", false, 0, 0, 0},
		{"2026-10-06\n", false, 0, 0, 0},
		{" 2026-10-06", false, 0, 0, 0},
		{"2026-1-10", true, 2026, 1, 10},
		{"2026-10-1x", false, 0, 0, 0},
		{"٢٠٢٦-10-06", true, 2026, 10, 6},
		{"2026-10-٠6", false, 0, 0, 0},
		{"2026-10-1٣", true, 2026, 10, 13},
		{"2026-10-2٣", true, 2026, 10, 23},
	} {
		got, ok := StrptimeDate(c.in)
		if ok != c.ok || ok && (got.Year != c.y || got.Month != c.m || got.Day != c.d) {
			t.Errorf("StrptimeDate(%q) = %v, %v; want %v %d-%d-%d", c.in, got, ok, c.ok, c.y, c.m, c.d)
		}
	}
}
