"""Write internal/contacts/pytables.go and internal/py/spacetable.go from the running CPython's str.casefold and str.isspace.

Run from the repo root: nix develop --impure -c python tools/contacts/gen_tables.py
"""

import subprocess
import sys
import unicodedata

OUT = "internal/contacts/pytables.go"
SPACE_OUT = "internal/py/spacetable.go"


def go_string(s):
    out = []
    for ch in s:
        c = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append(f"\\u{c:04x}")
        else:
            out.append(f"\\U{c:08x}")
    return '"' + "".join(out) + '"'


def main():
    chars = [chr(c) for c in range(0x80, sys.maxunicode + 1) if not 0xD800 <= c <= 0xDFFF]
    fold = [(ord(ch), ch.casefold()) for ch in chars if ch.casefold() != ch]
    v = sys.version_info
    space = [ord(ch) for ch in chars if ch.isspace()]
    out = [
        "// Code generated by tools/contacts/gen_tables.py; DO NOT EDIT.",
        "",
        "package contacts",
        "",
        f"// pyFold maps every non-ASCII code point to its CPython {v.major}.{v.minor} str.casefold() form"
        f" (Unicode {unicodedata.unidata_version}) where that differs from the code point.",
        "var pyFold = map[rune]string{",
    ]
    out += [f"\t0x{c:04x}: {go_string(f)}," for c, f in fold]
    out += ["}", ""]
    space_out = [
        "// Code generated by tools/contacts/gen_tables.py; DO NOT EDIT.",
        "",
        "package py",
        "",
        "// spaceTable holds every non-ASCII code point for which str.isspace() is true.",
        "var spaceTable = map[rune]bool{",
    ]
    space_out += [f"\t0x{c:04x}: true," for c in space]
    space_out += ["}", ""]
    for path, lines in ((OUT, out), (SPACE_OUT, space_out)):
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        subprocess.run(["gofmt", "-w", path], check=True)


if __name__ == "__main__":
    main()
