"""Write internal/assistant/loop/blockorder_table.go from the anthropic SDK's beta content block models.

The Python loop journals each response block as model_dump(mode="json", exclude_unset=True): the model's
declared fields in declaration order, then any extra keys in wire order, recursively for nested models. The
table lists, per model, its `type` literals and its fields with the models a field may hold.

Run from the repo root: nix develop --impure -c python tools/anthropic/gen_blockorder.py
"""

import inspect
import subprocess
import typing

import anthropic
from anthropic.types.beta import BetaContentBlock
from pydantic import BaseModel

OUT = "internal/assistant/loop/blockorder_table.go"


def models_in(annotation, out):
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        if annotation not in out:
            out.append(annotation)
        return
    for arg in typing.get_args(annotation):
        models_in(arg, out)


def walk(model, seen):
    if model.__name__ in seen:
        return
    seen[model.__name__] = None
    fields = []
    for name, info in model.model_fields.items():
        nested = []
        models_in(info.annotation, nested)
        fields.append((info.alias or name, [m.__name__ for m in nested]))
        for m in nested:
            walk(m, seen)
    kind = model.model_fields.get("type")
    seen[model.__name__] = (list(typing.get_args(kind.annotation)) if kind else [], fields)


def go_strings(values):
    values = list(values)
    if not values:
        return "nil"
    return "[]string{" + ", ".join(f'"{v}"' for v in values) + "}"


def main():
    roots = []
    models_in(BetaContentBlock, roots)
    seen = {}
    for root in roots:
        walk(root, seen)
    lines = [
        "// Code generated by tools/anthropic/gen_blockorder.py from anthropic-python " + anthropic.__version__ + "; DO NOT EDIT.",
        "",
        "package loop",
        "",
        "var blockRoots = " + go_strings(m.__name__ for m in roots),
        "",
        "var blockModels = map[string]blockModel{",
    ]
    for name in sorted(seen):
        types, fields = seen[name]
        lines.append(f"\t\"{name}\": {{types: {go_strings(types)}, fields: []blockField{{")
        for field, nested in fields:
            lines.append(f"\t\t{{\"{field}\", {go_strings(nested)}}},")
        lines.append("\t}},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    subprocess.run(["gofmt", "-w", OUT], check=True)


if __name__ == "__main__":
    main()
