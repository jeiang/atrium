"""Write internal/pyhtml/entities.go from the running CPython's html module tables.

Run from the repo root: nix develop --impure -c python tools/pyhtml/gen_entities.py
"""

import html
import subprocess
import sys
from html.entities import html5

OUT = "internal/pyhtml/entities.go"


def go_string(s):
    out = []
    for ch in s:
        c = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append(f"\\u{c:04x}")
        else:
            out.append(f"\\U{c:08x}")
    return '"' + "".join(out) + '"'


def main():
    v = sys.version_info
    out = [
        "// Code generated by tools/pyhtml/gen_entities.py; DO NOT EDIT.",
        "",
        "package pyhtml",
        "",
        f"// html5 is CPython {v.major}.{v.minor} html.entities.html5: entity names, with and without the semicolon,"
        " to their replacement text.",
        "var html5 = map[string]string{",
    ]
    out += [f"\t{go_string(k)}: {go_string(val)}," for k, val in sorted(html5.items())]
    out += ["}", "", "// invalidCharrefs is html._invalid_charrefs.", "var invalidCharrefs = map[int64]string{"]
    out += [f"\t0x{k:x}: {go_string(val)}," for k, val in sorted(html._invalid_charrefs.items())]
    out += ["}", "", "// invalidCodepoints is html._invalid_codepoints.", "var invalidCodepoints = map[int64]bool{"]
    out += [f"\t0x{k:x}: true," for k in sorted(html._invalid_codepoints)]
    out += ["}", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    subprocess.run(["gofmt", "-w", OUT], check=True)


if __name__ == "__main__":
    main()
