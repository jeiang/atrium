"""Write internal/mail/mime/pytables.go from the running CPython's str methods and codecs.

Run from the repo root: nix develop --impure -c python tools/mime/gen_tables.py
"""

import importlib
import pkgutil
import subprocess
import sys
import unicodedata

import encodings
import encodings.aliases

OUT = "internal/mail/mime/pytables.go"
SIGMA = "\u03a3"


def ranges(points):
    out = []
    for c in points:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def range_table(name, doc, points):
    r16 = [r for r in ranges(points) if r[1] <= 0xFFFF]
    r32 = [r for r in ranges(points) if r[0] > 0xFFFF]
    split = [r for r in ranges(points) if r[0] <= 0xFFFF < r[1]]
    for lo, hi in split:
        r16.append([lo, 0xFFFF])
        r32.insert(0, [0x10000, hi])
    out = [f"// {doc}", f"var {name} = &unicode.RangeTable{{", "\tR16: []unicode.Range16{"]
    out += [f"\t\t{{0x{lo:04x}, 0x{hi:04x}, 1}}," for lo, hi in r16]
    out += ["\t},", "\tR32: []unicode.Range32{"]
    out += [f"\t\t{{0x{lo:x}, 0x{hi:x}, 1}}," for lo, hi in r32]
    out += ["\t},", "}", ""]
    return out


def go_string(s):
    out = []
    for ch in s:
        c = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append(f"\\u{c:04x}")
        else:
            out.append(f"\\U{c:08x}")
    return '"' + "".join(out) + '"'


def main():
    points = range(sys.maxunicode + 1)
    chars = [chr(c) for c in points if not 0xD800 <= c <= 0xDFFF]
    cased, ignorable = [], []
    for ch in chars:
        if ch == SIGMA:
            continue
        after = ("A" + SIGMA + ch).lower()[1]
        between = ("A" + ch + SIGMA).lower()[-1]
        if after == "\u03c3":
            cased.append(ord(ch))
        elif between == "\u03c2":
            ignorable.append(ord(ch))
    lower = [(ord(ch), ch.lower()) for ch in chars if ord(ch) >= 0x80 and ch != SIGMA and ch.lower() != ch]
    space = [ord(ch) for ch in chars if ch.isspace()]
    digit = [ord(ch) for ch in chars if ch.isdigit()]
    decimal = [ord(ch) for ch in chars if unicodedata.decimal(ch, None) is not None]
    for c in decimal:
        assert unicodedata.decimal(chr(c)) == (c - next(lo for lo, hi in ranges(decimal) if lo <= c <= hi)) % 10, hex(c)

    charmaps = {}
    for mod in pkgutil.iter_modules(encodings.__path__):
        try:
            m = importlib.import_module("encodings." + mod.name)
        except ImportError:
            continue
        table = getattr(m, "decoding_table", None)
        if isinstance(table, str) and len(table) == 256:
            charmaps[mod.name] = table
    modules = sorted(m.name for m in pkgutil.iter_modules(encodings.__path__))

    v = sys.version_info
    out = [
        "// Code generated by tools/mime/gen_tables.py; DO NOT EDIT.",
        "",
        "package mime",
        "",
        'import "unicode"',
        "",
        f"// pyLower maps every non-ASCII code point other than U+03A3 to its CPython {v.major}.{v.minor} str.lower()"
        f" form (Unicode {unicodedata.unidata_version}) where that differs from the code point.",
        "var pyLower = map[rune]string{",
    ]
    out += [f"\t0x{c:04x}: {go_string(lo)}," for c, lo in lower]
    out += ["}", ""]
    out += range_table("pyCased", "pyCased is CPython's cased set as str.lower() applies it to a final sigma.", cased)
    out += range_table(
        "pyCaseIgnorable", "pyCaseIgnorable is CPython's case-ignorable set as str.lower() applies it to a final sigma.", ignorable
    )
    out += range_table("pySpace", "pySpace is every code point for which str.isspace() is true.", space)
    out += range_table("pyDigit", "pyDigit is every code point for which str.isdigit() is true.", digit)
    out += range_table(
        "pyDecimal",
        "pyDecimal is every code point int() reads as a digit; each range starts at a zero or continues a run of tens.",
        decimal,
    )
    out += [
        "// pyCodecAliases is encodings.aliases.aliases: normalized encoding names to codec module names.",
        "var pyCodecAliases = map[string]string{",
    ]
    out += [f"\t{go_string(k)}: {go_string(val)}," for k, val in sorted(encodings.aliases.aliases.items())]
    out += ["}", "", "// pyCodecModules lists every module in the encodings package.", "var pyCodecModules = map[string]bool{"]
    out += [f"\t{go_string(m)}: true," for m in modules]
    out += [
        "}",
        "",
        "// pyCharmaps holds the 256-character decoding table of every charmap codec; U+FFFE marks an undefined byte.",
        "var pyCharmaps = map[string]string{",
    ]
    out += [f"\t{go_string(name)}: {go_string(table)}," for name, table in sorted(charmaps.items())]
    out += ["}", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    subprocess.run(["gofmt", "-w", OUT], check=True)


if __name__ == "__main__":
    main()
