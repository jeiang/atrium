package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/jeiang/atrium/internal/config"
	"github.com/jeiang/atrium/internal/settings"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: settingsgen OUTPUT_DIR")
		os.Exit(2)
	}
	if err := generate(os.Args[1], settings.Default.Defs()); err != nil {
		fmt.Fprintln(os.Stderr, "settingsgen:", err)
		os.Exit(1)
	}
}

func generate(dir string, all []settings.Def) error {
	var defs []settings.Def
	for _, d := range all {
		if d.Class != settings.Fixed {
			defs = append(defs, d)
		}
	}
	slices.SortFunc(defs, func(a, b settings.Def) int {
		return strings.Compare(config.TOMLName(a), config.TOMLName(b))
	})
	schema, err := schemaJSON(defs)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, body := range map[string]string{
		"atrium.schema.json": schema,
		"environment.md":     environmentDoc(defs),
		"reference.md":       referenceDoc(defs),
	} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func schemaType(d settings.Def) any {
	switch d.Type {
	case settings.Int:
		return []string{"integer", "string"}
	case settings.Float:
		return []string{"number", "string"}
	case settings.Bool:
		return []string{"boolean", "string"}
	}
	return "string"
}

func schemaDefault(d settings.Def) any {
	switch d.Type {
	case settings.Int:
		if n, err := strconv.ParseInt(d.Default, 10, 64); err == nil {
			return n
		}
	case settings.Float:
		if f, err := strconv.ParseFloat(d.Default, 64); err == nil {
			return f
		}
	case settings.Bool:
		return d.Default == "true"
	}
	return d.Default
}

func schemaJSON(defs []settings.Def) (string, error) {
	modules := map[string]any{}
	for _, d := range defs {
		module, _ := modules[d.Module].(map[string]any)
		if module == nil {
			module = map[string]any{"type": "object", "additionalProperties": false, "properties": map[string]any{}}
			modules[d.Module] = module
		}
		props := module["properties"].(map[string]any)
		if !d.Secret {
			prop := map[string]any{"type": schemaType(d)}
			if len(d.Choices) > 0 {
				prop["enum"] = d.Choices
			}
			if d.Default != "" {
				prop["default"] = schemaDefault(d)
			}
			props[d.Key] = prop
		}
		props[d.Key+"_file"] = map[string]any{"type": "string", "description": "path of a file holding the value"}
	}
	root := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"title":                "atrium configuration",
		"type":                 "object",
		"additionalProperties": false,
		"properties":           modules,
	}
	out, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return "", err
	}
	return string(out) + "\n", nil
}

func environmentDoc(defs []settings.Def) string {
	var b strings.Builder
	b.WriteString("# Environment variables\n\n")
	b.WriteString("Generated by `just settingsgen`. Do not edit.\n\n")
	b.WriteString("An environment variable pins its setting and wins over the configuration file and the stored value. The file named by `" + config.ConfigEnv + "` is the only other source of pins.\n\n")
	b.WriteString("| Variable | Setting |\n| --- | --- |\n")
	for _, d := range defs {
		fmt.Fprintf(&b, "| `%s` | `%s` |\n", config.EnvName(d), config.TOMLName(d))
	}
	return b.String()
}

func referenceDoc(defs []settings.Def) string {
	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("Generated by `just settingsgen`. Do not edit.\n\n")
	b.WriteString("The file named by `" + config.ConfigEnv + "` is TOML with one table per module. Unknown keys are refused. A string value may contain `${NAME}` references to environment variables; an unset variable is refused. `<key>_file` reads the value from a file and trims it; secret settings accept only `<key>_file`. A secret setting's environment variable also has a `_FILE` form naming a file whose trimmed contents are the value; setting both forms is refused. Every key set here or through its environment variable is pinned: it shows read-only and cannot be changed with `atrium settings`. Precedence: environment variable, configuration file, stored value, default.\n")
	module := ""
	for _, d := range defs {
		if d.Module != module {
			module = d.Module
			fmt.Fprintf(&b, "\n## %s\n\n| Key | Type | Default | Class | Environment variable |\n| --- | --- | --- | --- | --- |\n", module)
		}
		typ := string(d.Type)
		if len(d.Choices) > 0 {
			typ += " (" + strings.Join(d.Choices, ", ") + ")"
		}
		def := "none"
		if d.Default != "" {
			def = "`" + d.Default + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | `%s` |\n", d.Key, typ, def, d.Class, config.EnvName(d))
	}
	return b.String()
}
